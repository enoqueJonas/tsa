import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
const authored = readFileSync("packages/runtime-kernel/src/paths/delivery-ci-dependency-worked.ts", "utf8");
const wired = readFileSync("packages/runtime-kernel/src/paths/delivery-continuous-integration-deep.ts", "utf8");
assert.ok(wired.includes('id === "jobs-stages" ? [...sections, ...ciDependencyWorked]'), "Learner source is not attached to actual jobs-stages reading");
const match = authored.match(/export const ciDependencyPython = ("(?:\\.|[^"\\])*");/);
assert.ok(match, "Exact published Python CI source not found");
const source = JSON.parse(match[1]);
const run = (...args) => spawnSync("python3", ["-c", source, ...args], {encoding:"utf8",timeout:12000});
const yes = run(); assert.ifError(yes.error); assert.equal(yes.status,0,yes.stderr);
assert.match(yes.stdout,/image_build: PASSED/);
assert.match(yes.stdout,/publish: PASSED/);
assert.match(yes.stdout,/candidate: ELIGIBLE/);
const no = run("--fail-unit"); assert.ifError(no.error); assert.equal(no.status,17,no.stderr);
assert.match(no.stdout,/unit_test: FAILED/);
assert.match(no.stdout,/image_build: BLOCKED/);
assert.match(no.stdout,/publish: BLOCKED/);
assert.match(no.stdout,/candidate: REJECTED/);
console.log("Delivery CI authored Python dependency gate: positive eligible, negative test blocks image and publish.");